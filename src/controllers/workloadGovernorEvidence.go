package controllers

import (
	"context"
	"time"

	"content-management-system/src/workload"
	"gorm.io/gorm"
)

type workloadHealthCorrelation struct {
	IncidentID string     `json:"incident_id"`
	Service    string     `json:"service"`
	Class      string     `json:"class"`
	StartedAt  time.Time  `json:"started_at"`
	ResolvedAt *time.Time `json:"resolved_at,omitempty"`
	Decisions  int64      `json:"decisions"`
	WouldDefer int64      `json:"would_defer"`
	Href       string     `json:"href"`
}

func workloadHealthCorrelations(db *gorm.DB, start, end time.Time) ([]workloadHealthCorrelation, error) {
	ctx, cancel := context.WithTimeout(context.Background(), 2*time.Second)
	defer cancel()
	rows := []workloadHealthCorrelation{}
	// Bound the owner episodes before joining the indexed request-time ledger.
	// No additional probe or incident is generated by this evidence read.
	err := db.WithContext(ctx).Raw(`WITH episodes AS (
		SELECT public_id,root_service,first_detected_at,resolved_at
		FROM system_incident_episodes
		WHERE first_detected_at>=? AND first_detected_at<?
		ORDER BY first_detected_at DESC LIMIT 20
	)
	SELECT e.public_id::text AS incident_id,e.root_service AS service,d.class,
		e.first_detected_at AS started_at,e.resolved_at,
		count(*) AS decisions,
		count(*) FILTER (WHERE d.would_verdict IN ('defer','blocked','admit_reduced')) AS would_defer
	FROM episodes e JOIN workload_decisions d ON d.event='request'
		AND d.created_at>=GREATEST(?,e.first_detected_at-INTERVAL '10 minutes')
		AND d.created_at<LEAST(?,COALESCE(e.resolved_at,?)+INTERVAL '10 minutes')
	GROUP BY e.public_id,e.root_service,e.first_detected_at,e.resolved_at,d.class
	ORDER BY e.first_detected_at DESC LIMIT 100`, start, end, start, end, end).Scan(&rows).Error
	if err != nil {
		return []workloadHealthCorrelation{}, err
	}
	out := make([]workloadHealthCorrelation, 0, len(rows))
	for _, row := range rows {
		class, ok := workload.Class(row.Class)
		if !ok {
			continue
		}
		affected := workloadIncidentResources(row.Service)
		overlaps := false
		for _, a := range affected {
			for _, resource := range class.Resources {
				overlaps = overlaps || resource == a
			}
		}
		if !overlaps {
			continue
		}
		row.Href = "/platform/system-health?tab=incidents&incident=" + row.IncidentID
		out = append(out, row)
	}
	return out, nil
}
